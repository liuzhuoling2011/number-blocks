// GitHub Pages for this repo publishes the main branch root (legacy source).
// Copy the Vite build next to index.html and point model/font URLs at public/,
// which already holds one.glb, pad.glb, and the font. Vite dev/build do not use
// this mirror; pages-entry.js does.
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const dist = path.join(root, 'dist');
const assetsDir = path.join(root, 'assets');

const html = await readFile(path.join(dist, 'index.html'), 'utf8');
const jsName = html.match(/src="\/number-blocks\/assets\/([^"]+\.js)"/)?.[1];
const cssName = html.match(/href="\/number-blocks\/assets\/([^"]+\.css)"/)?.[1];
if (!jsName || !cssName) {
  throw new Error('dist/index.html is missing the built /number-blocks/assets files');
}

await rm(assetsDir, { recursive: true, force: true });
await mkdir(assetsDir, { recursive: true });
await cp(path.join(dist, 'assets'), assetsDir, { recursive: true });

async function rewrite(name, from, to) {
  const file = path.join(assetsDir, name);
  const source = await readFile(file, 'utf8');
  if (!source.includes(from)) {
    throw new Error(`${name} is missing ${from}`);
  }
  await writeFile(file, source.replaceAll(from, to));
}

await rewrite(jsName, '/number-blocks/models/', '/number-blocks/public/models/');
await rewrite(cssName, '/number-blocks/fonts/', '/number-blocks/public/fonts/');

await writeFile(
  path.join(root, 'pages-entry.js'),
  `// Generated by scripts/sync-pages-root.mjs — do not edit.
// Loaded only when GitHub Pages serves this repository root as-is.
const style = document.createElement('link');
style.rel = 'stylesheet';
style.href = new URL('./assets/${cssName}', import.meta.url).href;
document.head.appendChild(style);
await import('./assets/${jsName}');
`,
);

await writeFile(path.join(root, '.nojekyll'), '');
